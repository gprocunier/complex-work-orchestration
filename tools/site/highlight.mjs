// Build-time only: published pages need neither JavaScript nor a syntax service.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { parse, parseFragment } from 'parse5';
import { codeToHtml } from 'shiki';

export const THEME = 'github-dark-default';
const generatedThemes = new Set(['github-light', 'github-dark', THEME]);
const languages = new Set(['bash', 'json', 'text']);
function* elements(node, tag) {
  if (node.tagName === tag) yield node;
  for (const child of node.childNodes ?? []) yield* elements(child, tag);
}
export function textContent(node) {
  return node.nodeName === '#text' ? node.value : (node.childNodes ?? []).map(textContent).join('');
}
function attribute(tag, name, value) {
  // Only fixed build-owned names and Shiki's trusted theme values enter here.
  const escaped = value.replaceAll('&', '&amp;').replaceAll('"', '&quot;');
  const pattern = new RegExp(`\\s${name}=(?:"[^"]*"|'[^']*')`, 'i');
  const rendered = ` ${name}="${escaped}"`;
  return pattern.test(tag) ? tag.replace(pattern, rendered) : tag.replace(/>$/, `${rendered}>`);
}

export async function highlightHtml(source) {
  const edits = [];
  const styles = new Map();
  const styleClass = declaration => {
    const name = `shiki-style-${createHash('sha256').update(declaration).digest('hex').slice(0, 16)}`;
    styles.set(name, declaration);
    return name;
  };
  let count = 0;
  for (const pre of elements(parse(source, { sourceCodeLocationInfo: true }), 'pre')) {
    const attrs = Object.fromEntries(pre.attrs.map(({ name, value }) => [name, value]));
    const lang = attrs['data-language'];
    if (!languages.has(lang)) throw new Error(`Code box needs explicit data-language (bash, json or text), got ${lang}`);
    const children = (pre.childNodes ?? []).filter(n => n.tagName === 'code');
    if (children.length !== 1 || pre.childNodes.some(n => n !== children[0] && (n.tagName || textContent(n).trim()))) {
      throw new Error('Each code box must contain exactly one code element');
    }
    const code = children[0];
    const original = textContent(code);
    const highlighted = await codeToHtml(original, { lang, theme: THEME });
    const generated = [...elements(parseFragment(highlighted), 'pre')][0];
    const outputCode = [...elements(generated, 'code')][0];
    if (textContent(outputCode) !== original) throw new Error('Highlighting changed code text');
    // Extract Shiki's own styles into a local stylesheet. Keep the preview's
    // strict style-src 'self' policy; never enable unsafe-inline for tokens.
    const inner = highlighted.match(/<code>([\s\S]*)<\/code>/)[1]
      .replace(/style="([^"]*)"/g, (_, declaration) => `class="${styleClass(declaration)}"`);
    const classes = (attrs.class ?? '').split(/\s+/).filter(c => c && c !== 'shiki' && !generatedThemes.has(c) && !c.startsWith('shiki-style-'));
    const location = pre.sourceCodeLocation;
    let start = source.slice(location.startTag.startOffset, location.startTag.endOffset);
    start = start.replace(/\sstyle=(?:"[^"]*"|'[^']*')/i, '');
    const base = styleClass(generated.attrs.find(a => a.name === 'style').value);
    start = attribute(start, 'class', [...classes, 'shiki', THEME, base].join(' '));
    start = attribute(start, 'data-theme', THEME);
    edits.push([location.startTag.startOffset, location.startTag.endOffset, start]);
    edits.push([code.sourceCodeLocation.startTag.endOffset, code.sourceCodeLocation.endTag.startOffset, inner]);
    count++;
  }
  for (const [start, end, replacement] of edits.sort((a, b) => b[0] - a[0])) {
    source = source.slice(0, start) + replacement + source.slice(end);
  }
  return { html: source, count, styles };
}

async function main() {
  const mode = process.argv[2];
  if (!['--check', '--write'].includes(mode) || process.argv.length !== 3) {
    throw new Error('Usage: node highlight.mjs --check|--write');
  }
  const docs = fileURLToPath(new URL('../../docs/', import.meta.url));
  // Prepare and validate the entire projection before writing any page.
  const changes = [];
  const styles = new Map();
  let count = 0;
  for (const file of (await readdir(docs)).filter(f => f.endsWith('.html')).sort()) {
    const path = join(docs, file);
    const original = await readFile(path, 'utf8');
    const result = await highlightHtml(original);
    count += result.count;
    for (const [name, declaration] of result.styles) styles.set(name, declaration);
    if (result.html !== original) changes.push([path, result.html]);
  }
  const cssPath = join(docs, 'shiki.css');
  const css = `/* Generated by tools/site/highlight.mjs using Shiki ${THEME}. Do not edit. */\n`
    + [...styles].sort(([a], [b]) => a.localeCompare(b)).map(([name, declaration]) =>
      `.shiki.${name}, .shiki .${name} { ${declaration} }\n`).join('');
  if (await readFile(cssPath, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; }) !== css) changes.push([cssPath, css]);
  if (mode === '--write') {
    for (const [path, html] of changes) await writeFile(path, html);
  }
  console.log(`${count} Shiki ${THEME} code boxes; ${changes.length} files ${mode === '--write' ? 'updated' : 'out of date'}.`);
  if (mode === '--check' && changes.length) process.exitCode = 1;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
