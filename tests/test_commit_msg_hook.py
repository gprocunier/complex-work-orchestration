from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[1]
HOOK = ROOT / "tools/hooks/commit-msg"
NAME = "Ordinary Contributor"
EMAIL = "contributor@example.invalid"


class CommitMessageHookTests(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory(prefix="commit-message-hook-")
        self.addCleanup(temporary.cleanup)
        self.repo = Path(temporary.name)
        self.env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
        self.env.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull,
                        GIT_TERMINAL_PROMPT="0")
        self.git("init", "--quiet", "--template=")
        for setting, value in (("user.name", NAME), ("user.email", EMAIL),
                               ("core.hooksPath", str(HOOK.parent)), ("commit.gpgsign", "false"),
                               ("maintenance.auto", "false"), ("gc.auto", "0")):
            self.git("config", "--local", setting, value)
        self.message = self.repo / "message.txt"

    def git(self, *args: str, check: bool = True,
            extra_env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
        return subprocess.run(["git", *args], cwd=self.repo, env={**self.env, **(extra_env or {})},
                              capture_output=True, text=True, check=check, timeout=15)

    def hook(self, message: str = "Improve contributor documentation\n", *,
             extra_env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
        self.message.write_text(message, encoding="utf-8")
        before = self.message.read_bytes()
        result = subprocess.run([str(HOOK), str(self.message)], cwd=self.repo,
                                env={**self.env, **(extra_env or {})}, capture_output=True,
                                text=True, check=False, timeout=15)
        self.assertEqual(self.message.read_bytes(), before, "the hook must not rewrite messages")
        return result

    def assert_refused(self, result: subprocess.CompletedProcess[str], reason: str) -> None:
        self.assertNotEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("commit-msg:", result.stderr)
        self.assertIn(reason, result.stderr)
        self.assertNotIn("Traceback", result.stderr)

    def test_repository_hook_is_executable_and_not_installed(self) -> None:
        self.assertTrue(HOOK.is_file())
        self.assertTrue(os.access(HOOK, os.X_OK))
        projection = json.loads((ROOT / "policy/install-projection.yaml").read_text())
        self.assertIn("tools", {entry["path"] for entry in projection["excluded"]})
        self.assertNotIn("tools", {entry["path"] for entry in projection["entries"]})

    def test_accepts_ordinary_subjects_bodies_and_technical_tool_mentions(self) -> None:
        for message in (
            "Improve contributor documentation\n",
            "Fix Codex integration\n\nKeep Git configuration portable.\n",
            "Document AI model configuration\n\nExplain the API response fields.\n",
            "Support W123 and F12 identifiers\n\nPreserve M20, M1beta and UTF-8 text: café.\n",
            "Keep SW01, F3D and AM2 identifiers intact\n",
            "Fix parser output\n\nThe file is generated by the parser.\n",
        ):
            with self.subTest(message=message):
                result = self.hook(message)
                self.assertEqual(result.returncode, 0, result.stderr)

    def test_refuses_attribution_trailers_in_subject_or_body(self) -> None:
        for trailer in (
            "Co-authored-by: Someone <someone@example.invalid>",
            "Signed-off-by: Someone <someone@example.invalid>",
            "  co-AUTHORED-BY : Codex <tool@example.invalid>",
            "Reviewed-by: Someone <someone@example.invalid>",
            "Generated-by: Another Tool",
        ):
            for prefix in ("", "Improve documentation\n\n"):
                with self.subTest(trailer=trailer, prefix=prefix):
                    self.assert_refused(self.hook(prefix + trailer + "\n"), "attribution")

    def test_refuses_tool_and_ai_attribution(self) -> None:
        for attribution in (
            "Generated with Codex",
            "🤖 Generated with [Claude Code](https://example.invalid)",
            "Written using an AI assistant",
            "This change was implemented by ChatGPT.",
            "Thanks to GitHub Copilot for the implementation.",
            "AI-assisted implementation",
            "LLM generated changes",
            "Developed with a tool",
            "Generated with Future Assistant",
            "Co-authored with Claude",
            "Pair-programmed with Codex",
            "This commit was made with Cursor.",
            "With assistance from an AI assistant.",
        ):
            for prefix in ("", "Improve documentation\n\n"):
                with self.subTest(attribution=attribution, prefix=prefix):
                    self.assert_refused(self.hook(prefix + attribution + "\n"), "attribution")

    def test_refuses_internal_codes_in_subject_or_body(self) -> None:
        for code in ("W01", "W99.I2", "F3", "F9", "cwor-example.2", "M1a", "M1b", "M2",
                     "w04", "f3", "CWOR-example", "m1a", "m2"):
            for prefix in ("Fix ", "Improve documentation\n\nComplete "):
                with self.subTest(code=code, prefix=prefix):
                    self.assert_refused(self.hook(prefix + code + " work\n"), "internal tracking")

    def test_refuses_each_effective_identity_override(self) -> None:
        for role in ("AUTHOR", "COMMITTER"):
            for field, value in (("NAME", "Different Contributor"), ("EMAIL", "other@example.invalid")):
                with self.subTest(role=role, field=field):
                    self.assert_refused(self.hook(extra_env={f"GIT_{role}_{field}": value}),
                                        role.lower() + " identity")

    def test_accepts_matching_environment_identities(self) -> None:
        result = self.hook(extra_env={"GIT_AUTHOR_NAME": NAME, "GIT_AUTHOR_EMAIL": EMAIL,
                                     "GIT_COMMITTER_NAME": NAME, "GIT_COMMITTER_EMAIL": EMAIL})
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_accepts_another_contributors_configured_identity(self) -> None:
        for name, email in (("Another Contributor", "another@example.invalid"),
                            ("Zoë Example", "zoe@example.invalid"),
                            ("Claude Example", "claude@example.invalid")):
            with self.subTest(name=name):
                self.git("config", "--local", "user.name", name)
                self.git("config", "--local", "user.email", email)
                result = self.hook()
                self.assertEqual(result.returncode, 0, result.stderr)

    def test_accepts_inherited_contributor_configuration(self) -> None:
        global_config = self.repo / "contributor.gitconfig"
        for setting, value in (("user.name", NAME), ("user.email", EMAIL)):
            self.git("config", "--local", "--unset", setting)
            self.git("config", "--file", str(global_config), setting, value)
        result = self.hook(extra_env={"GIT_CONFIG_GLOBAL": str(global_config)})
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_missing_configured_identity_refuses_even_with_environment_identity(self) -> None:
        overrides = {"GIT_AUTHOR_NAME": NAME, "GIT_AUTHOR_EMAIL": EMAIL,
                     "GIT_COMMITTER_NAME": NAME, "GIT_COMMITTER_EMAIL": EMAIL}
        for setting in ("user.name", "user.email"):
            with self.subTest(setting=setting):
                previous = self.git("config", "--local", "--get", setting).stdout.strip()
                self.git("config", "--local", "--unset", setting)
                self.assert_refused(self.hook(extra_env=overrides), setting)
                self.git("config", "--local", setting, previous)

    def test_empty_configured_identity_refuses(self) -> None:
        for setting in ("user.name", "user.email"):
            with self.subTest(setting=setting):
                previous = self.git("config", "--local", "--get", setting).stdout.strip()
                self.git("config", "--local", setting, "  ")
                self.assert_refused(self.hook(), setting)
                self.git("config", "--local", setting, previous)

    def test_git_commit_uses_hook_and_keeps_configured_identity(self) -> None:
        self.message.write_text("Improve contributor documentation\n", encoding="utf-8")
        result = self.git("commit", "--quiet", "--allow-empty", "-F", str(self.message), check=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        identities = self.git("log", "-1", "--format=%an <%ae>%n%cn <%ce>").stdout.splitlines()
        self.assertEqual(identities, [f"{NAME} <{EMAIL}>"] * 2)

    def test_git_commit_refuses_explicit_author_and_environment_committer(self) -> None:
        self.message.write_text("Improve contributor documentation\n", encoding="utf-8")
        for args, env, reason in (
            (("--author=Someone Else <someone@example.invalid>",), {}, "author identity"),
            ((), {"GIT_COMMITTER_NAME": "Someone Else"}, "committer identity"),
        ):
            with self.subTest(reason=reason):
                result = self.git("commit", "--quiet", "--allow-empty", "-F", str(self.message),
                                  *args, check=False, extra_env=env)
                self.assert_refused(result, reason)
                self.assertNotEqual(self.git("rev-parse", "--verify", "HEAD", check=False).returncode, 0)

    def test_git_commit_refuses_message(self) -> None:
        self.message.write_text("Improve documentation\n\nComplete W01 work.\n", encoding="utf-8")
        self.assert_refused(self.git("commit", "--quiet", "--allow-empty", "-F", str(self.message),
                                    check=False), "internal tracking")
        self.assertNotEqual(self.git("rev-parse", "--verify", "HEAD", check=False).returncode, 0)

    def test_bad_invocation_and_unreadable_message_refuse_clearly(self) -> None:
        for args in ([], [str(self.repo / "missing-message")]):
            with self.subTest(args=args):
                result = subprocess.run([str(HOOK), *args], cwd=self.repo, env=self.env,
                                        capture_output=True, text=True, check=False, timeout=15)
                self.assert_refused(result, "message")


if __name__ == "__main__":
    unittest.main()
